using System;
using System.Collections.Generic;

namespace EmberKeeper;

public sealed class EncGroup
{
    public string Name { get; set; } = "";
    public int Count { get; set; } = 1;
    public int Hp { get; set; } = 10;
    public int Ac { get; set; } = 12;
    public string Color { get; set; } = "#7c2a2c";
}

public sealed class EncounterSpec
{
    public string Terrain { get; set; } = "";
    public List<EncGroup> Groups { get; set; } = new();
    public string Activity { get; set; } = "";
    public string Twist { get; set; } = "";
    public string Loot { get; set; } = "";
    public string Weather { get; set; } = "";
}

public sealed class GenRow
{
    public string Label { get; set; } = "";
    public string Value { get; set; } = "";
    public GenRow() { }
    public GenRow(string label, string value) { Label = label; Value = value; }
}

public sealed class GenResult
{
    public string Title { get; set; } = "";
    public string Main { get; set; } = "";
    public string Caption { get; set; } = "";
    public List<GenRow> Rows { get; set; } = new();
    public EncounterSpec? Encounter { get; set; }

    /// <summary>Для связей: два узла и подпись линии.</summary>
    public string? BondA { get; set; }
    public string? BondB { get; set; }
    public string? BondLabel { get; set; }
    public string? BondNote { get; set; }
}

