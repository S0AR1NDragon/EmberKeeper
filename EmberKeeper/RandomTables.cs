    public static int Next(int minInclusive, int maxExclusive) => R.Next(minInclusive, maxExclusive);
    public static int Dice(int sides) => R.Next(1, sides + 1);
    public static int Dice(int count, int sides) { int s = 0; for (int i = 0; i < count; i++) s += Dice(sides); return s; }
    public static string Pick(params string[] a) => a[R.Next(a.Length)];
    public static string Pick(IReadOnlyList<string> a) => a[R.Next(a.Count)];
    public static string Maybe(string text, int chance = 50) => R.Next(100) < chance ? text : "";

