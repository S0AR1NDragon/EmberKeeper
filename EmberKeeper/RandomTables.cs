    {
        var kind = BondKinds[R.Next(BondKinds.Length)];
        var role = Pick(kind.Roles);

        var res = new GenResult
        {
            Title = kind.Kind,
            Main = "«" + role + "»",
            Caption = "Связь между двумя персонажами — игроками или игроком и НПС.",
