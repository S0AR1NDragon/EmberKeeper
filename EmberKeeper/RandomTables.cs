    public static GenResult Encounter()
    {
        var terrain = Terrains[R.Next(Terrains.Length)];
        var pickCount = 1 + (R.Next(100) < 35 ? 1 : 0); // иногда две группы
        var spec = new EncounterSpec { Terrain = terrain.Name, Weather = Pick(EncWeather) };
        var used = new HashSet<string>();

        for (int i = 0; i < pickCount; i++)
        {
            var g = terrain.Groups[R.Next(terrain.Groups.Length)];
            if (!used.Add(g.Name)) continue;
            int count = R.Next(g.Min, g.Max + 1);
            spec.Groups.Add(new EncGroup
            {
                Name = g.Name,
                Count = count,
                Hp = g.Hp,
                Ac = g.Ac,
                Color = g.Name.Contains("Волк") || g.Name.Contains("Медведь") || g.Name.Contains("паук") ||
                        g.Name.Contains("Кабан") || g.Name.Contains("Крыса") || g.Name.Contains("Ящер") ||
                        g.Name.Contains("Комары") || g.Name.Contains("Грифон") || g.Name.Contains("Гарпия") ||
                        g.Name.Contains("козёл") || g.Name.Contains("Кобольд") || g.Name.Contains("Слизь")
                    ? "#4d5a3c"
                    : "#7c2a2c",
            });
        }

        spec.Activity = Pick(Activities);
        spec.Twist = Pick(terrain.Twists);
        spec.Loot = LootLine();

        int totalHp = 0;
        foreach (var g in spec.Groups) totalHp += g.Hp * g.Count;

        var res = new GenResult
        {
            Title = "Случайная стычка",
            Main = terrain.Name,
            Caption = $"{spec.Activity}. Погода: {spec.Weather}.",
            Encounter = spec,
        };

        foreach (var g in spec.Groups)
            res.Rows.Add(new GenRow("Противник", $"{g.Name} × {g.Count} (ХП {g.Hp}, КД {g.Ac})"));

        res.Rows.Add(new GenRow("Обстоятельство", spec.Activity));
        res.Rows.Add(new GenRow("Опасность", spec.Twist));
        res.Rows.Add(new GenRow("Погода", spec.Weather));
        res.Rows.Add(new GenRow("Добыча", spec.Loot));
        res.Rows.Add(new GenRow("Сложность", totalHp < 30 ? "лёгкая — до 3 раундов" : totalHp < 80 ? "средняя — на 5-6 раундов" : "серьёзная — с расходом ресурсов"));
        return res;
    }

